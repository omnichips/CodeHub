/** Each glyph as a list of lit pixels, and its width. */
export const FONT: Record<string, { w: number; px: [number, number][] }> = Object.fromEntries(Object.entries(GLYPHS).map(([ch, g]) => {
  const rows = g.split('|'), px: [number, number][] = [];
  rows.forEach((r, y) => [...r].forEach((c, x) => { if (c === '#') px.push([x, y]); }));
  return [ch, { w: Math.max(...rows.map((r) => r.length)), px }];
}));
export const LINE_H = 10; // a line of text, descenders and a pixel between included
const CELL = 6; // a monospace cell

/** The text as a voice shows it: the radio and the loudspeaker in capitals. */
export const shown = (text: string, voice: Voice) => (voice === 'radio' || voice === 'loudspeaker' ? text.toUpperCase() : text);
/** The pixels each character takes, its gap included, in a voice. */
export const advance = (ch: string, voice: Voice) => (voice === 'jec' ? CELL : (FONT[ch]?.w ?? 4) + 1);
/** How wide a run of text is in a voice (the trailing gap left off). */
export const measure = (text: string, voice: Voice) => Math.max(0, [...shown(text, voice)].reduce((n, ch) => n + advance(ch, voice), 0) - 1);
/** Characters the font has no glyph for. */
export const missing = (text: string) => [...new Set([...text.toUpperCase(), ...text])].filter((ch) => !FONT[ch]);

/** Words packed into lines no wider than `width`. */
export function wrap(text: string, voice: Voice, width: number): string[] {
  const lines: string[] = [];
  for (const word of text.split(' ')) {
    const last = lines.at(-1);
    if (last !== undefined && measure(`${last} ${word}`, voice) <= width) lines[lines.length - 1] = `${last} ${word}`;
    else lines.push(word);
  }
  return lines;
}
